def plural(n: int, one: str, few: str, many: str) -> str:
    """Русское склонение при числе: 1 задача, 2 задачи, 5 задач.

    Нужно потому, что количество задач живёт в переменной: без склонения
    заголовок превращается в «И ещё 13 задачи».
    """
    tail = abs(n) % 100
    if 11 <= tail <= 14:
        return many
    tail %= 10
    if tail == 1:
        return one
    if 2 <= tail <= 4:
        return few
    return many

